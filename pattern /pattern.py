# pattern based

for i in range(0,10,2):
    for j in range(0,i+1,2):
        print(i,end='')
    print('')
print()

for m in range(8,-1,-2):
    for n in range(m+1,0,-2):
        print(m,end='')
    print('')
print()

for a in range(4):
    for b in range(4,a,-1):
        print(b,end='')
    print('')
print()

